uint16_t decodeColor(uint8_t val) {
  switch (val) {
    case 1: return 0xFFFF;
    case 2: return 0xD922;
    case 3: return 0x28AE;
    default: return 0x0000;
  }
}

void drawRLEImage(const uint8_t *data, size_t dataSize, uint8_t w, uint8_t h, uint8_t oX, uint8_t oY, bool main = true) {
  uint8_t x = 0;
  uint8_t y = 0;
  uint16_t i = 0;

  while (i < dataSize) {
    uint8_t entry = pgm_read_byte(&data[i++]);
    uint8_t val = entry >> 6;
    uint8_t count = entry & 0x3F;
    uint16_t color = decodeColor(val);

    for (uint8_t c = 0; c < count; c++) {
      if (main) {
tft.drawPixel(x + oX, y + oY, color);
      } else {
tft2.drawPixel(x + oX, y + oY, color);
      }
      
      x++;
      if (x >= w) {
        x = 0;
        y++;
      }
    }
  }
}
